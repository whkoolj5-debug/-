import {mkdir,writeFile} from 'node:fs/promises';
import {Store} from '../src/store.js';
import {Economy} from '../src/economy.js';
import {Service} from '../src/service.js';
import {renderTable,handImage} from '../src/art.js';
import {embed,publicRows} from '../src/ui.js';
import {replayState} from '../src/table-view.js';
const dir=process.argv[2]||'work/preview';
await mkdir(dir,{recursive:true});
const store=new Store(':memory:');const economy=new Economy(store),service=new Service(store,economy);
const t=await service.create('preview','guild','channel','a','로얄스트레이트',10000);
t.demo=true;
for(const [n,name] of ['김포커','민지','리버헌터','에이스','칩리더','행운의클로버'].entries())await service.join(t,String(n),name,n+1);
service.blinds(t,'a',200,100);
await writeFile(`${dir}/01-lobby.png`,await renderTable(t));
service.start(t,'a');
await writeFile(`${dir}/02-preflop.png`,await renderTable(t));
while(!t.hand.done&&t.hand.street==='preflop')service.action(t,t.hand.turn,'call',null,t.hand.rev);
await writeFile(`${dir}/03-flop.png`,await renderTable(t));
await writeFile(`${dir}/private-hand.png`,await handImage(t.hand.holeCards.a));
while(!t.hand.done)service.action(t,t.hand.turn,t.hand.seats[t.hand.turn].bet<t.hand.currentBet?'call':'check',null,t.hand.rev);
await service.finish(t);
await writeFile(`${dir}/04-showdown.png`,await renderTable(t));
for(const theme of ['midnight','burgundy']){t.theme=theme;await writeFile(`${dir}/theme-${theme}.png`,await renderTable(t));}
await writeFile(`${dir}/public-history.json`,JSON.stringify(t.history,null,2));
await writeFile(`${dir}/discord-payload.json`,JSON.stringify({embed:embed(t,'test').toJSON(),components:publicRows(t).map(r=>r.toJSON())},null,2));
const replay=replayState(t,1,0);await writeFile(`${dir}/replay-first-step.png`,await renderTable(replay.table));
console.log(`Preview process peak RSS: ${(process.resourceUsage().maxRSS/1024).toFixed(1)} MiB`);
store.close();console.log(`Preview images saved: ${dir}`);
